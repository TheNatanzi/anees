"""PG-37 one box per line (Medi 2026-10-08 "Can we turn this into just 1 box and we can write the correction, not try
and separate into so many boxes?"). The server half of the one box:

  build-prompt   scripts/correction_parse_prompt.md -> supabase/functions/parse-correction/prompt.ts (one source of truth)
  read-notes     every 'note' row (his words the page could not shape, and the AI read was off) gets ONE Claude Haiku
                 read (`claude -p --model claude-haiku-5-5`, the same prompt file), logged like every paid call
                 (scripts/track.py run line with cost; data/budget.json 'anthropic'); the structured rows it yields are
                 inserted into transcript_corrections (payload.raw = his words, payload.parsed_from = the note id) and
                 added to the mirror so this hour's build sees them. A note that yields nothing stays a note (never
                 re-read: payload.parsed_from on a 'note' child marks it done).
  mirror-spend   the edge function's api_spend rows (service anthropic, note 'parse-correction ...') become
                 data/budget.json calls + run lines, so check_rules AI-paid-logged sees every paid call.
  run            read-notes + mirror-spend (what `medi_corrections.py pull` calls; fail-open, never blocks a publish)

Nothing here edits a raw transcript (S2) and nothing asks Amal anything."""
import datetime as dt
